//! Embed the SiteBox skills into the binary.
//!
//! Sols must be able to read the same doctrine the terminal agent uses, without
//! a skills folder at runtime and without a network call. The files are plain
//! markdown, so the binary grows by ~300 KB and every build carries the exact
//! skills that shipped with it.

use std::fs;
use std::path::{Path, PathBuf};

fn main() {
    let manifest = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").unwrap());
    let skills = manifest.parent().unwrap_or(&manifest).join("skills");
    println!("cargo:rerun-if-changed={}", skills.display());

    let mut files: Vec<(String, String, PathBuf)> = Vec::new();
    if let Ok(dirs) = fs::read_dir(&skills) {
        let mut dirs: Vec<_> = dirs.flatten().map(|e| e.path()).collect();
        dirs.sort();
        for dir in dirs {
            if !dir.is_dir() || !dir.join("SKILL.md").is_file() {
                continue;
            }
            let name = dir
                .file_name()
                .unwrap_or_default()
                .to_string_lossy()
                .to_string();
            collect(&dir, &dir, &name, &mut files);
        }
    }
    files.sort_by(|a, b| a.0.cmp(&b.0).then(a.1.cmp(&b.1)));

    let mut out = String::from("// @generated by build.rs — do not edit\n");
    out.push_str("pub static SKILL_FILES: &[(&str, &str, &str)] = &[\n");
    for (skill, rel, abs) in &files {
        println!("cargo:rerun-if-changed={}", abs.display());
        out.push_str(&format!(
            "({:?}, {:?}, include_str!({:?})),\n",
            skill,
            rel,
            abs.to_string_lossy()
        ));
    }
    out.push_str("];\n");

    let dest = PathBuf::from(std::env::var("OUT_DIR").unwrap()).join("skills_embedded.rs");
    fs::write(dest, out).expect("write generated skills");
}

fn collect(dir: &Path, root: &Path, skill: &str, out: &mut Vec<(String, String, PathBuf)>) {
    let Ok(rd) = fs::read_dir(dir) else { return };
    let mut entries: Vec<_> = rd.flatten().map(|e| e.path()).collect();
    entries.sort();
    for p in entries {
        if p.is_dir() {
            collect(&p, root, skill, out);
        } else if p.extension().and_then(|e| e.to_str()) == Some("md") {
            let rel = p
                .strip_prefix(root)
                .unwrap_or(&p)
                .to_string_lossy()
                .replace('\\', "/");
            out.push((skill.to_string(), rel, p));
        }
    }
}
